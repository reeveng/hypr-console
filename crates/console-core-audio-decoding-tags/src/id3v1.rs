  use console_core_never::Never;
  use console_core_number_conversion::index;

  use super::GENRES;

  pub fn genre_name(number: u8) -> Result<Option<&'static &'static str>, Never> {
    let Ok(at) = index(number);

    Ok(GENRES.get(at))
  }
