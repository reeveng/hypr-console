fn split(work: &mut [f32; 32], size: u32, cos: &[f32]) -> Result<(), Never> {
  let Ok(width) = index(size);
  let Ok(half) = index(size.div_euclid(2));
  let mut joined = [0f32; 32];

  for block in work.chunks_exact_mut(width.max(1)) {
    let pairs = block.iter().zip(block.iter().rev()).take(half);
    let sums = pairs.clone().map(|(front, back)| front + back);
    let differences = pairs
      .zip(cos)
      .map(|((front, back), cos_2)| (front - back) * cos_2);

    for (slot, value) in joined.iter_mut().zip(sums.chain(differences)) {
      *slot = value;
    }

    for (slot, value) in block.iter_mut().zip(joined.iter()) {
      *slot = *value;
    }
  }

  Ok(())
}

fn join(work: &mut [f32; 32], size: u32) -> Result<(), Never> {
  let Ok(width) = index(size);
  let Ok(half) = index(size.div_euclid(2));
  let mut joined = [0f32; 32];

  for block in work.chunks_exact_mut(width.max(1)) {
    let second = block.iter().skip(half);
    let sums = second
      .clone()
      .zip(second.skip(1))
      .map(|(a, b)| a + b)
      .chain(block.last().copied());
    let interleaved = block
      .iter()
      .take(half)
      .zip(sums)
      .flat_map(|(even, odd)| [*even, odd]);

    for (slot, value) in joined.iter_mut().zip(interleaved) {
      *slot = value;
    }

    for (slot, value) in block.iter_mut().zip(joined.iter()) {
      *slot = *value;
    }
  }

  Ok(())
}

fn dct32(x: &[f32; 32]) -> Result<[f32; 32], Never> {
  let mut work = *x;

  split(&mut work, 32, &COS_16)?;
  split(&mut work, 16, &COS_8)?;
  split(&mut work, 8, &COS_4)?;
  split(&mut work, 4, &COS_2)?;

  for [front, back] in work.as_chunks_mut::<2>().0.iter_mut() {
    let (a, b) = (*front, *back);

    *front = a + b;
    *back = (a - b) * COS_1;
  }

  join(&mut work, 4)?;
  join(&mut work, 8)?;
  join(&mut work, 16)?;
  join(&mut work, 32)?;

  Ok(work)
}

fn next_vector(d: &[f32; 32]) -> Result<[f32; 64], Never> {
  let negated = |value: &f32| -*value;
  let high = d.iter().skip(17);
  let low = d.iter().skip(1).take(15);

  let ordered = d
    .iter()
    .skip(16)
    .take(1)
    .copied()
    .chain(high.clone().copied())
    .chain(std::iter::once(0.0))
    .chain(high.rev().map(negated))
    .chain(d.iter().skip(16).take(1).map(negated))
    .chain(low.clone().rev().map(negated))
    .chain(d.iter().take(1).map(negated))
    .chain(low.map(negated));

  let mut vector = [0f32; 64];

  for (slot, value) in vector.iter_mut().zip(ordered) {
    *slot = value;
  }

  Ok(vector)
}

pub fn synthesis(
  state: &mut SynthesisState,
  slots: u32,
  samples: &[f32],
  out: &mut [f32],
) -> Result<(), Never> {
  match slots {
    0 => return Ok(()),
    _ => {}
  }

  let Ok(stride) = index(slots);

  for (slot_in_granule, block) in out.as_chunks_mut::<32>().0.iter_mut().enumerate() {
    let mut subbands = [0f32; 32];

    for (slot, value) in subbands
      .iter_mut()
      .zip(samples.iter().skip(slot_in_granule).step_by(stride.max(1)))
    {
      *slot = *value;
    }

    let Ok(transformed) = dct32(&subbands);
    let Ok(vector) = next_vector(&transformed);

    state.v_vec.rotate_right(1);

    for newest in state.v_vec.first_mut().into_iter() {
      *newest = vector;
    }

    let mut accumulated = [0f32; 32];

    let windows = SYNTHESIS_D.as_chunks::<64>().0.iter();

    for (pair, window) in state.v_vec.as_chunks::<2>().0.iter().zip(windows) {
      let [near, far] = pair;

      for ((sum, v), d) in accumulated.iter_mut().zip(near.iter()).zip(window.iter()) {
        *sum += v * d;
      }

      for ((sum, v), d) in accumulated
        .iter_mut()
        .zip(far.iter().skip(32))
        .zip(window.iter().skip(32))
      {
        *sum += v * d;
      }
    }

    for (slot, sum) in block.iter_mut().zip(accumulated) {
      *slot = sum.clamp(-1.0, 1.0);
    }
  }

  Ok(())
}

