  fn every_byte_round_trips_and_keeps_its_order() {
    let mut previous = None;

    for byte in u8::MIN..=u8::MAX {
      let opcode = Opcode::from_byte(byte);
      let Ok(encoded) = opcode.to_byte();
      assert_eq!(encoded, byte);

      match previous {
        Some(earlier) => assert!(earlier < opcode),
        None => {}
      }

      previous = Some(opcode);
    }
  }
