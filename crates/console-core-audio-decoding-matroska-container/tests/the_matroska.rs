//! A Matroska file of four tracks and two clusters is demuxed, and the tracks, packets, tags and seeks that come out are held.
//!
//! The bytes are a segment of unknown size holding a seek head, the info, four audio tracks (PCM, Vorbis with Xiph-laced
//! private data, FLAC with a stream info block, Opus), a sized cluster of plain, Xiph-laced, EBML-laced, fixed-size-laced
//! and grouped blocks, an unknown-size cluster, the tags and, in one of the two files, the cues. They were written out of
//! the reader this crate was taken from, and what that reader made of them is what the constants at the end say.

use std::error::Error;
use std::io::Cursor;

use console_core_audio_decoding_interfaces::errors::Error as DecodeFault;
use console_core_audio_decoding_interfaces::formats::{
  FormatOptions, FormatReader, SeekMode, SeekTo,
};
use console_core_audio_decoding_interfaces::units::Time;
use console_core_audio_decoding_matroska_container::MkvReader;
use console_core_byte_streams::{MediaSourceStream, MediaSourceStreamOptions, ReadOnlySource};
use console_core_iteration::{Step, iterate};
use console_core_never::Never;

fn open(bytes: &[u8]) -> Result<MkvReader, DecodeFault> {
  let Ok(stream) = MediaSourceStream::new(
    Box::new(Cursor::new(bytes.to_vec())),
    MediaSourceStreamOptions::default(),
  );

  MkvReader::try_new(stream, &FormatOptions::default())
}

fn packets(reader: &mut MkvReader) -> Result<Vec<String>, Box<dyn Error>> {
  let seen = iterate((reader, Vec::new()), |(reader_2, mut seen)| {
    Ok(match reader_2.next_packet() {
      Ok(packet) => {
        let Ok(value_1) = packet.track_id();
        let Ok(value_2) = packet.ts();
        let Ok(value_3) = packet.dur();
        let Ok(value_4) = packet.buf();
        let payload = match std::str::from_utf8(value_4) {
          Ok(text) => text,
          Err(fault) => return Ok(Step::Halt(Err(fault))),
        };

        seen.push(format!("{value_1} {value_2} {value_3} {payload}"));

        Step::Again((reader_2, seen))
      }
      Err(_the_packets_ran_out) => Step::Halt(Ok(seen)),
    })
  })?;

  seen.map_err(Into::into)
}

fn refusal(bytes: &[u8]) -> Result<String, Never> {
  Ok(match open(bytes) {
    Ok(_opened) => String::from("opened"),
    Err(fault) => fault.to_string(),
  })
}

#[test]
fn the_tracks_say_what_each_codec_is() -> Result<(), Box<dyn Error>> {
  let reader = open(&WITH_CUES)?;
  let Ok(value_5) = reader.tracks();

  let seen: Vec<String> = value_5
    .iter()
    .map(|track| format!("{} {:?} {:?}", track.id, track.language, track.codec_params))
    .collect();

  assert_eq!(seen, GOLDEN_TRACKS);

  Ok(())
}

#[test]
fn every_lacing_comes_out_as_its_frames() -> Result<(), Box<dyn Error>> {
  let mut reader = open(&WITH_CUES)?;

  let seen = packets(&mut reader)?;

  assert_eq!(seen, GOLDEN_PACKETS);

  Ok(())
}

#[test]
fn the_tags_are_read_from_where_the_seek_head_says() -> Result<(), Box<dyn Error>> {
  let mut reader = open(&WITH_CUES)?;
  let Ok(metadata) = reader.metadata();
  let Ok(current) = metadata.current();
  let seen: Vec<String> = match current {
    Some(revision) => {
      let Ok(value_6) = revision.tags();

      value_6
        .iter()
        .map(|tag| format!("{} {:?}", tag.key, tag.value))
        .collect()
    }
    None => Vec::new(),
  };

  assert_eq!(seen, GOLDEN_TAGS);

  Ok(())
}

#[test]
fn seeking_by_cues_lands_on_the_cluster_and_reads_on() -> Result<(), Box<dyn Error>> {
  let mut reader = open(&WITH_CUES)?;
  let Ok(value_7) = Time::new(2, 0.0);

  let to = reader.seek(
    SeekMode::Accurate,
    SeekTo::Time {
      time: value_7,
      track_id: Some(1),
    },
  )?;
  let rest = packets(&mut reader)?;

  assert_eq!(format!("{to:?}"), GOLDEN_SEEK_CUES);
  assert_eq!(rest, GOLDEN_AFTER_CUES);

  Ok(())
}

#[test]
fn seeking_without_cues_walks_forward() -> Result<(), Box<dyn Error>> {
  let mut reader = open(&WITHOUT_CUES)?;
  let to = reader.seek(
    SeekMode::Accurate,
    SeekTo::TimeStamp {
      ts: 1033,
      track_id: 4,
    },
  )?;
  let rest = packets(&mut reader)?;

  assert_eq!(format!("{to:?}"), GOLDEN_SEEK_FORWARD);
  assert_eq!(rest, GOLDEN_AFTER_FORWARD);

  Ok(())
}

#[test]
fn a_seek_before_the_first_cue_or_to_a_missing_track_is_refused() -> Result<(), Box<dyn Error>> {
  let mut reader = open(&WITH_CUES)?;
  let early = reader.seek(SeekMode::Accurate, SeekTo::TimeStamp { ts: 3, track_id: 1 });
  let missing = reader.seek(SeekMode::Accurate, SeekTo::TimeStamp { ts: 3, track_id: 9 });

  assert_eq!(format!("{early:?}"), GOLDEN_EARLY);
  assert_eq!(format!("{missing:?}"), GOLDEN_MISSING);

  Ok(())
}

#[test]
fn a_stream_that_cannot_seek_is_read_through_to_its_end() -> Result<(), Box<dyn Error>> {
  let Ok(source) = ReadOnlySource::new(Cursor::new(WITH_CUES.to_vec()));
  let Ok(stream) = MediaSourceStream::new(Box::new(source), MediaSourceStreamOptions::default());
  let mut reader = MkvReader::try_new(stream, &FormatOptions::default())?;

  let seen = packets(&mut reader)?;

  assert_eq!(seen, GOLDEN_PACKETS);

  Ok(())
}

