pub fn orientation(character: char) -> Result<Orientation, Never> {
  let code = u32::from(character);
  let ending =
    NOT_ROTATED.get(NOT_ROTATED.partition_point(|(_first, last, _orientation)| *last < code));

  Ok(match ending {
    Some((first, _last, orientation)) => match first.cmp(&code) {
      core::cmp::Ordering::Less | core::cmp::Ordering::Equal => *orientation,
      core::cmp::Ordering::Greater => Orientation::Rotated,
    },
    None => Orientation::Rotated,
  })
}
