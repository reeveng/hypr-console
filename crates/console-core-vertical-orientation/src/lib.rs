//! Which way a character stands when the text it is in runs down the page.
//!
//! Unicode says it for every character in annex #50, the Vertical_Orientation
//! property: upright as in the code charts, turned ninety degrees clockwise
//! with the line, or drawn from a glyph of its own with either of those to
//! fall back to. The SVG reader asks it of every cluster in text whose writing
//! mode runs top to bottom, and turns the ones that stand upright.
//!
//! The answer is a table of the ranges that are not turned, because that is
//! the short list: everything else, Latin, Greek, Arabic and the code points
//! nobody has assigned, turns with the line. The ranges are sorted and apart,
//! so a character is looked up by the first range that does not end before
//! it, and is in it or in none. Ranges side by side with the same answer are
//! one range here, where the property file lists them a block at a time.
//!
//! The crate began as unicode-vo, by Evgeniy Reizner under MIT or Apache-2.0,
//! carried in `forks/` for the SVG reader, and the table is still the one it
//! generated from revision 17 of `VerticalOrientation.txt`. Moving to a later
//! revision changes what some characters answer, so it is a change of its own
//! with the file it was made from, not a side effect of this one.

