//! The arrangements themselves, converted out of wvkbd's `layout.mobintl.h`.
//!
//! Data, and long. It is written down rather than worked out because there is
//! nothing to work out: which letter sits under which thumb is a decision
//! somebody made about a keyboard, and the only thing to do with it is keep it.
//!
//! `layout.rs` is the shape of all this and the reading of it. The alphabets
//! are `keymap`'s: an arrangement names one, and what its keys produce is
//! whatever the system's xkb symbols say that alphabet is.

use super::{Key, Kind, Layout, key, mods};
