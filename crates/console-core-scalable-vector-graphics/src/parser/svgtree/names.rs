struct Map<V: 'static> {
    pub key: u64,
    pub disps: &'static [(u32, u32)],
    pub entries: &'static [(&'static str, V)],
}

impl<V: PartialEq> Map<V> {
    fn get(&self, key: &str) -> Result<Option<&V>, console_core_never::Never> {
        let Ok(digest) = hash(key, self.key);
        let Ok((bucket, f1, f2)) = split(digest);
        let Ok(bucket_count) = console_core_number_conversion::fixed_index(self.disps.len());
        let index = match u64::from(bucket).checked_rem(bucket_count) {
            Some(index) => index,
            None => return Ok(None),
        };
        let Ok(bucket_index) = console_core_number_conversion::index(index);
        let (d1, d2) = match self.disps.get(bucket_index) {
            Some(&displacement) => displacement,
            None => return Ok(None),
        };
        let Ok(displaced) = displace(DisplaceArguments { f1, f2, d1, d2 });
        let Ok(entry_count) = console_core_number_conversion::fixed_index(self.entries.len());
        let table_index = match u64::from(displaced).checked_rem(entry_count) {
            Some(index_2) => index_2,
            None => return Ok(None),
        };
        let Ok(entry_index) = console_core_number_conversion::index(table_index);

        match self.entries.get(entry_index) {
            Some((name, value)) => match (*name).cmp(key) {
                core::cmp::Ordering::Equal => Ok(Some(value)),
                core::cmp::Ordering::Less | core::cmp::Ordering::Greater => Ok(None),
            },
            None => Ok(None),
        }
    }

    fn key(&self, value: &V) -> Result<&'static str, console_core_never::Never> {
        match self.entries.iter().find(|(_, found)| found == value) {
            Some((name, _)) => Ok(name),
            None => {
                console_core_logging::error!("SVG name missing from the generated name table");

                Ok("")
            }
        }
    }
}

#[inline]
fn hash(x: &str, key: u64) -> core::result::Result<u64, console_core_never::Never> {
    use std::hash::Hasher;

    let mut hasher = siphasher::sip::SipHasher13::new_with_keys(0, key);
    hasher.write(x.as_bytes());

    Ok(hasher.finish())
}

#[inline]
fn split(hash: u64) -> core::result::Result<(u32, u32, u32), console_core_never::Never> {
    const BITS: u32 = 21;
    const MASK: u64 = 0x1F_FFFF;

    Ok((match ::console_core_number_conversion::wrapped::<_, ::core::primitive::u32>(hash & MASK) { ::core::result::Result::Ok(converted_position) => converted_position },
     match ::console_core_number_conversion::wrapped::<_, ::core::primitive::u32>(::core::primitive::u64::wrapping_shr(hash, BITS) & MASK) { ::core::result::Result::Ok(converted_position) => converted_position },
     match ::console_core_number_conversion::wrapped::<_, ::core::primitive::u32>(::core::primitive::u64::wrapping_shr(hash, ::core::primitive::u32::wrapping_mul(2, BITS)) & MASK) { ::core::result::Result::Ok(converted_position) => converted_position }))
}

#[inline]
fn displace(
  DisplaceArguments { f1, f2, d1, d2 }: DisplaceArguments,
) -> core::result::Result<u32, console_core_never::Never> {
    Ok(::core::primitive::u32::wrapping_add(::core::primitive::u32::wrapping_add(d2, ::core::primitive::u32::wrapping_mul(f1, d1)), f2))
}

struct DisplaceArguments {
  f1: u32,
  f2: u32,
  d1: u32,
  d2: u32,
}
