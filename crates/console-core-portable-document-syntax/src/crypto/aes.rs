struct AESCore;

impl AESCore {
  fn substitute(state: &mut [u8; 16], table: &[u8; 256]) -> Result<(), Never> {
    for byte in state {
      let Ok(substituted) = table_byte(table, *byte);
      *byte = substituted;
    }

    Ok(())
  }

  fn shift_rows(state: &mut [u8; 16]) -> Result<(), Never> {
    let [
      a0,
      a1,
      a2,
      a3,
      a4,
      a5,
      a6,
      a7,
      a8,
      a9,
      a10,
      a11,
      a12,
      a13,
      a14,
      a15,
    ] = *state;
    *state = [
      a0, a5, a10, a15, a4, a9, a14, a3, a8, a13, a2, a7, a12, a1, a6, a11,
    ];

    Ok(())
  }

  fn inv_shift_rows(state: &mut [u8; 16]) -> Result<(), Never> {
    let [
      a0,
      a1,
      a2,
      a3,
      a4,
      a5,
      a6,
      a7,
      a8,
      a9,
      a10,
      a11,
      a12,
      a13,
      a14,
      a15,
    ] = *state;
    *state = [
      a0, a13, a10, a7, a4, a1, a14, a11, a8, a5, a2, a15, a12, a9, a6, a3,
    ];

    Ok(())
  }

  fn mix_columns(state: &mut [u8; 16]) -> Result<(), Never> {
    let (columns, _remaining) = state.as_chunks_mut::<4>();

    for column in columns {
      let [a, b, c, d] = *column;
      let Ok([a2, b2, c2, d2]) = transform_word(*column, &MUL2);
      let Ok([a3, b3, c3, d3]) = transform_word(*column, &MUL3);
      *column = [
        a2 ^ b3 ^ c ^ d,
        a ^ b2 ^ c3 ^ d,
        a ^ b ^ c2 ^ d3,
        a3 ^ b ^ c ^ d2,
      ];
    }

    Ok(())
  }

  fn inv_mix_columns(state: &mut [u8; 16]) -> Result<(), Never> {
    let (columns, _remaining) = state.as_chunks_mut::<4>();

    for column in columns {
      let Ok([a9, b9, c9, d9]) = transform_word(*column, &MUL9);
      let Ok([a11, b11, c11, d11]) = transform_word(*column, &MUL11);
      let Ok([a13, b13, c13, d13]) = transform_word(*column, &MUL13);
      let Ok([a14, b14, c14, d14]) = transform_word(*column, &MUL14);
      *column = [
        a14 ^ b11 ^ c13 ^ d9,
        a9 ^ b14 ^ c11 ^ d13,
        a13 ^ b9 ^ c14 ^ d11,
        a11 ^ b13 ^ c9 ^ d14,
      ];
    }

    Ok(())
  }
}

fn table_byte(table: &[u8; 256], value: u8) -> Result<u8, Never> {
  let Ok(position) = index(value);

  Ok(match table.get(position) {
    Some(byte) => *byte,
    None => 0,
  })
}

fn transform_word(word: [u8; 4], table: &[u8; 256]) -> Result<[u8; 4], Never> {
  Ok(word.map(|byte| {
    let Ok(mapped) = table_byte(table, byte);
    mapped
  }))
}

fn xor_block(state: &mut [u8; 16], mask: &[u8; 16]) -> Result<(), Never> {
  for (data, mask_byte) in state.iter_mut().zip(mask) {
    *data ^= mask_byte;
  }

  Ok(())
}

fn schedule_round(base: &[u8; 16], mut previous_word: [u8; 4]) -> Result<[u8; 16], Never> {
  let mut next = [0; 16];
  let (source_words, _source_tail) = base.as_chunks::<4>();
  let (target_words, _target_tail) = next.as_chunks_mut::<4>();

  for ([a, b, c, d], target) in source_words.iter().zip(target_words) {
    let [p0, p1, p2, p3] = previous_word;
    *target = [a ^ p0, b ^ p1, c ^ p2, d ^ p3];
    previous_word = *target;
  }

  Ok(next)
}

fn final_word(block: &[u8; 16]) -> Result<[u8; 4], Never> {
  let [.., a, b, c, d] = *block;
  Ok([a, b, c, d])
}

fn scheduled_word(block: &[u8; 16], cycle: u8) -> Result<[u8; 4], Never> {
  let Ok([a, b, c, d]) = final_word(block);
  let Ok([first, second, third, fourth]) = transform_word([b, c, d, a], &S_BOX);

  Ok([first ^ cycle, second, third, fourth])
}

fn expand_key_128(round_keys: &mut [[u8; 16]], key: [u8; 16]) -> Result<(), Never> {
  let (initial, remaining) = match round_keys.split_first_mut() {
    Some(parts) => parts,
    None => return Ok(()),
  };
  *initial = key;
  let mut previous = key;

  for (target, round_constant) in remaining.iter_mut().zip(RCON) {
    let Ok(word) = scheduled_word(&previous, round_constant);
    let Ok(round) = schedule_round(&previous, word);
    *target = round;
    previous = round;
  }

  Ok(())
}

fn expand_key_256(round_keys: &mut [[u8; 16]], key: [[u8; 16]; 2]) -> Result<(), Never> {
  let (first, second, remaining) = match round_keys {
    [first, second, remaining @ ..] => (first, second, remaining),
    [] | [_] => return Ok(()),
  };
  let [mut even, mut odd] = key;
  *first = even;
  *second = odd;

  for (round, round_constant) in remaining.chunks_mut(2).zip(RCON) {
    let Ok(even_word) = scheduled_word(&odd, round_constant);
    let Ok(even_key) = schedule_round(&even, even_word);

    match round {
      [even_slot, odd_slot] => {
        *even_slot = even_key;
        let Ok(last_word) = final_word(&even_key);
        let Ok(odd_word) = transform_word(last_word, &S_BOX);
        let Ok(odd_key) = schedule_round(&odd, odd_word);
        *odd_slot = odd_key;
        even = even_key;
        odd = odd_key;
      }
      [last] => *last = even_key,
      [] | [_, _, _, ..] => {}
    }
  }

  Ok(())
}

pub(crate) enum Padding {
  Remove,
  Retain,
}

#[derive(Clone)]
pub(crate) struct AESCipher<const KEY_SIZE: usize, const ROUNDS: usize> {
  round_keys: [[u8; 16]; ROUNDS],
}

pub(crate) type AES128Cipher = AESCipher<16, 11>;
pub(crate) type AES256Cipher = AESCipher<32, 15>;

impl<const KEY_SIZE: usize, const ROUNDS: usize> AESCipher<KEY_SIZE, ROUNDS> {
  pub(crate) fn new(key: &[u8]) -> Result<Option<Self>, Never> {
    let mut round_keys = [[0_u8; 16]; ROUNDS];
    let (blocks, remainder) = key.as_chunks::<16>();

    match (KEY_SIZE, ROUNDS, blocks, remainder) {
      (16, 11, [block], []) => {
        let Ok(()) = expand_key_128(&mut round_keys, *block);
      }
      (32, 15, [first, second], []) => {
        let Ok(()) = expand_key_256(&mut round_keys, [*first, *second]);
      }
      _mismatched_key => return Ok(None),
    }

    Ok(Some(Self { round_keys }))
  }

  pub(crate) fn encrypt_block(&self, input: &[u8; 16]) -> Result<[u8; 16], Never> {
    let mut state = *input;
    let (first, last, middle) = match self.round_keys.as_slice() {
      [first, middle @ .., last] => (first, last, middle),
      [] | [_] => return Ok(state),
    };
    let Ok(()) = xor_block(&mut state, first);

    for key in middle {
      let Ok(()) = AESCore::substitute(&mut state, &S_BOX);
      let Ok(()) = AESCore::shift_rows(&mut state);
      let Ok(()) = AESCore::mix_columns(&mut state);
      let Ok(()) = xor_block(&mut state, key);
    }

    let Ok(()) = AESCore::substitute(&mut state, &S_BOX);
    let Ok(()) = AESCore::shift_rows(&mut state);
    let Ok(()) = xor_block(&mut state, last);

    Ok(state)
  }

  pub(crate) fn decrypt_block(&self, input: &[u8; 16]) -> Result<[u8; 16], Never> {
    let mut state = *input;
    let (first, last, middle) = match self.round_keys.as_slice() {
      [first, middle @ .., last] => (first, last, middle),
      [] | [_] => return Ok(state),
    };
    let Ok(()) = xor_block(&mut state, last);
    let Ok(()) = AESCore::inv_shift_rows(&mut state);
    let Ok(()) = AESCore::substitute(&mut state, &INV_S_BOX);

    for key in middle.iter().rev() {
      let Ok(()) = xor_block(&mut state, key);
      let Ok(()) = AESCore::inv_mix_columns(&mut state);
      let Ok(()) = AESCore::inv_shift_rows(&mut state);
      let Ok(()) = AESCore::substitute(&mut state, &INV_S_BOX);
    }

    let Ok(()) = xor_block(&mut state, first);

    Ok(state)
  }

  pub(crate) fn encrypt_cbc(&self, data: &[u8], iv: &[u8; 16]) -> Result<Vec<u8>, Never> {
    let (blocks, tail) = data.as_chunks::<16>();
    let Ok(tail_len) = console_core_number_conversion::wrapped::<_, u8>(tail.len());
    let padding = 16_u8.saturating_sub(tail_len);
    let mut final_block = [padding; 16];

    for (padding_byte, source) in final_block.iter_mut().zip(tail) {
      *padding_byte = *source;
    }

    let mut cipher = Vec::new();
    let mut previous = *iv;

    for block in blocks.iter().chain(core::iter::once(&final_block)) {
      let mut plaintext = *block;
      let Ok(()) = xor_block(&mut plaintext, &previous);
      let Ok(encrypted) = self.encrypt_block(&plaintext);
      cipher.extend_from_slice(&encrypted);
      previous = encrypted;
    }

    Ok(cipher)
  }

  pub(crate) fn decrypt_cbc(
    &self,
    data: &[u8],
    iv: &[u8; 16],
    padding: Padding,
  ) -> Result<Vec<u8>, Never> {
    let mut result = Vec::new();
    let mut previous = *iv;
    let (blocks, _remainder) = data.as_chunks::<16>();

    for block in blocks {
      let Ok(mut plaintext) = self.decrypt_block(block);
      let Ok(()) = xor_block(&mut plaintext, &previous);
      result.extend_from_slice(&plaintext);
      previous = *block;
    }

    let padding_len = match (padding, result.last().copied()) {
      (Padding::Remove, Some(length @ 1..=16)) => length,
      _keep_bytes => return Ok(result),
    };
    let Ok(length) = fixed_index(result.len());
    let start = match length.checked_sub(u64::from(padding_len)) {
      Some(start) => start,
      None => return Ok(result),
    };
    let Ok(position) = index(start);

    match result.get(position..) {
      Some(tail) => match tail.iter().all(|byte| *byte == padding_len).then_some(()) {
        Some(()) => result.truncate(position),
        None => {}
      },
      None => {}
    }

    Ok(result)
  }
}

