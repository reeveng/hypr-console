/// The arrangement a variant names.
///
/// A match, and not an index into a table standing beside the enum. The index
/// was what `as` on a fieldless enum is for, and what it rested on was three
/// hand-written orders agreeing -- the variants, `ALL`, and the table -- with
/// nothing anywhere checking that they did. Reordering any one of them moved
/// every arrangement after the change onto the wrong key, silently, and the
/// keyboard would have come up looking right and typing somebody else's
/// letters. Here each variant names its own keys, so there is no order left
/// for the three of them to disagree about.
///
/// Fifty-six arms is the point rather than the cost: an arm is a variant and
/// its arrangement said in one place, which is the thing the index could not
/// say.
