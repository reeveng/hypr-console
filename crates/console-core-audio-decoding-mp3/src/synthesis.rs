//! The polyphase synthesis filterbank: thirty-two subbands of a number of time
//! slots each (eighteen for layer three, twelve for layer one, thirty-six for
//! layer two), turned into thirty-two samples for each slot.
//!
//! Each time slot is a thirty-two point DCT of one sample from every subband,
//! kept in a first-in first-out list of sixteen results, and one output block
//! of thirty-two samples is the sum, over the list, of the results windowed
//! by the table the standard gives.
//!
//! The DCT is Byeong Gi Lee's fast algorithm: a block is split into sums and
//! scaled differences, each half is transformed the same way, and the two
//! are joined again. Upstream wrote that as recursion flattened into one
//! function body; here it runs by stages over the whole block, all the splits
//! down to pairs and then all the joins back up, which is the same arithmetic
//! on the same values in the same order for each output.

